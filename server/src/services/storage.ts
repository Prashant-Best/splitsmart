import { randomUUID } from 'node:crypto';
import { createReadStream, type ReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { config } from '../config';

export interface ReceiptFileType {
  mime: string;
  ext: string;
}

/**
 * Identifies a receipt from its first bytes ("magic numbers"). The Content-Type and file name
 * sent by the browser are not trusted: a renamed .html file is rejected, not served back.
 */
export function sniffReceiptType(data: Buffer): ReceiptFileType | null {
  const ascii = (start: number, end: number) => data.toString('latin1', start, end);
  if (data.length >= 3 && data[0] === 0xff && data[1] === 0xd8 && data[2] === 0xff) {
    return { mime: 'image/jpeg', ext: 'jpg' };
  }
  if (data.length >= 8 && data.subarray(0, 8).equals(Buffer.from('89504e470d0a1a0a', 'hex'))) {
    return { mime: 'image/png', ext: 'png' };
  }
  if (data.length >= 12 && ascii(0, 4) === 'RIFF' && ascii(8, 12) === 'WEBP') {
    return { mime: 'image/webp', ext: 'webp' };
  }
  if (data.length >= 5 && ascii(0, 5) === '%PDF-') return { mime: 'application/pdf', ext: 'pdf' };
  return null;
}

/** Where receipt files live. Local disk today; a Cloudinary or S3 version would implement this. */
export interface ReceiptStorage {
  save(data: Buffer, ext: string): Promise<string>;
  open(key: string): Promise<ReadStream>;
  remove(key: string): Promise<void>;
}

// Keys are generated by save(); anything else (e.g. "../../.env") is refused.
const KEY_PATTERN = /^[0-9a-f-]{36}\.(jpg|png|webp|pdf)$/;

export class LocalReceiptStorage implements ReceiptStorage {
  private readonly dir: string;

  constructor(dir: string) {
    this.dir = dir;
  }

  async save(data: Buffer, ext: string): Promise<string> {
    await mkdir(this.dir, { recursive: true });
    const key = `${randomUUID()}.${ext}`;
    await writeFile(this.pathFor(key), data, { flag: 'wx' });
    return key;
  }

  async open(key: string): Promise<ReadStream> {
    const file = this.pathFor(key);
    await stat(file); // throws ENOENT if the file is missing
    return createReadStream(file);
  }

  async remove(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
  }

  private pathFor(key: string): string {
    if (!KEY_PATTERN.test(key)) throw new Error('Invalid receipt key');
    return path.join(this.dir, key);
  }
}

export const receiptStorage: ReceiptStorage = new LocalReceiptStorage(config.uploadDir);
